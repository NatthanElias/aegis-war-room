"""Project constraint records for coding agents. Standard library only.

Each constraint is one file, .specs/constraints/<slug>.md, so developers on parallel fronts add records
without touching the same lines. A file that exists is active; superseding one deletes it and names it in
the new record's `replaces` bullet. INDEX.md is generated by `render`. `migrate` converts the retired
.specs/STATE.md decisions table into records. references/constraints.md owns the format.
"""

import argparse
import datetime as dt
import fnmatch
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

FILL = "[FILL]"
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
BULLET = re.compile(r"^- \*\*([^*]+)\*\*:[ \t]*(.*)$")
BULLETS = ("origin", "scope", "paths", "date", "replaces", "legacy-id")
REQUIRED = ("origin", "scope", "date")
HEADINGS = ("Decision", "Why", "Trade-offs", "Not decided here")
REQUIRED_HEADINGS = ("Decision", "Why")
ORIGIN = re.compile(r"feature [a-z0-9]+(?:-[a-z0-9]+)*|team D-\d{2,}(?:, D-\d{2,})*|adr \S+")
LEGACY_ID = re.compile(r"AD-\d+")
LINK = re.compile(r"\[[^\]]*\]\(([^)]*)\)")
GLOBAL, GLOBAL_LIMIT, STEM_LIMIT = "global", 15, 60
SCRIPT = "python3 .opencode/skills/feature-workflow/scripts/constraints.py"
INDEX_NOTE = (f"Generated by constraints.py from the records in this folder. Do not edit; on a merge conflict, "
              f"run `{SCRIPT} render`.")


def store(root):
    return Path(root) / ".specs" / "constraints"


def state_file(root):
    return Path(root) / ".specs" / "STATE.md"


def relative(root, path):
    return path.relative_to(root).as_posix()


def write(path, text):
    """Write with LF line ends on every platform, so a rendered INDEX.md matches across machines."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def split_list(value):
    return [item.strip() for item in value.split(",")]


def label(name):
    return "Why..." if name == "Why" else name


def heading_name(text):
    """Map a `##` heading to its required name; any heading starting with Why is the Why section."""
    if text.startswith("Why"):
        return "Why"
    return text if text in HEADINGS else None


def parse(text):
    """Split a record into title, bullets, sections, and structural problems, tolerating any defect."""
    lines = text.splitlines()
    problems, bullets, sections, order = [], {}, {}, []
    index = 0
    while index < len(lines) and not lines[index].strip():
        index += 1
    title = None
    if index < len(lines) and lines[index].startswith("# "):
        title = lines[index][2:].strip()
        index += 1
    if not title:
        problems.append("missing title line `# <one-line summary>`")
    # Context: None while reading header bullets, then the section being read, or "" under a rejected heading.
    current = None
    for line in lines[index:]:
        if line.startswith("## "):
            name = line[3:].strip()
            current = heading_name(name) or ""
            if not current:
                problems.append(f"unknown heading `## {name}`")
            elif current in sections:
                problems.append(f"duplicate heading `## {name}`")
                current = ""
            else:
                sections[current] = []
                order.append(current)
            continue
        if line.startswith("# "):
            problems.append(f"extra title line `{line.strip()}`")
            continue
        if current:
            sections[current].append(line)
            continue
        if current == "" or not line.strip():
            continue
        match = BULLET.match(line)
        if not match:
            problems.append(f"unknown bullet or text before `## Decision`: `{line.strip()}`")
        elif match[1] not in BULLETS:
            problems.append(f"unknown bullet `{match[1]}`")
        elif match[1] in bullets:
            problems.append(f"duplicate bullet `{match[1]}`")
        else:
            bullets[match[1]] = match[2].strip()
    bodies = {name: "\n".join(body).strip() for name, body in sections.items()}
    for name in REQUIRED_HEADINGS:
        if name not in sections:
            problems.append(f"missing heading `## {label(name)}`")
    if order != [name for name in HEADINGS if name in sections]:
        problems.append("headings out of order; use " + ", ".join(f"`## {name}`" for name in HEADINGS))
    return {"title": title, "bullets": bullets, "sections": bodies, "problems": problems}


def scopes_of(record):
    return [item for item in split_list(record["bullets"].get("scope", "")) if item]


def paths_of(record):
    value = record["bullets"].get("paths", "")
    return [item for item in split_list(value) if item] if value else []


def origin_problem(value):
    if not ORIGIN.fullmatch(value):
        return (f"invalid origin `{value}`; use `feature <slug>`, `team D-NN[, D-NN]`, or `adr <path>`")
    return None


def scope_problem(value):
    items = split_list(value)
    for item in items:
        if not SLUG.fullmatch(item):
            return f"invalid scope `{item}`; use lowercase words joined by single dashes"
    if len(set(items)) != len(items):
        return f"duplicate scope in `{value}`"
    if GLOBAL in items and len(items) > 1:
        return "scope `global` cannot be combined with other scopes"
    return None


def glob_problem(value):
    for item in split_list(value):
        if (not item or item.startswith("/") or "\\" in item or ":" in item
                or ".." in item.split("/")):
            return (f"invalid paths glob `{item}`; use a relative glob with forward slashes, "
                    f"no `..`, and no leading `/`")
    return None


def date_problem(value):
    try:
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
            raise ValueError
        dt.date.fromisoformat(value)
    except ValueError:
        return f"invalid date `{value}`; use YYYY-MM-DD"
    return None


def slug_problem(value, what="slug"):
    if not SLUG.fullmatch(value):
        return f"invalid {what} `{value}`; use lowercase letters and digits joined by single dashes"
    return None


CHECKS = {"origin": origin_problem, "scope": scope_problem, "paths": glob_problem, "date": date_problem,
          "replaces": lambda value: slug_problem(value, "replaces slug"),
          "legacy-id": lambda value: None if LEGACY_ID.fullmatch(value) else
          f"invalid legacy-id `{value}`; use AD-NNN"}


def links(body):
    """Return the relative link targets in a section, ignoring code spans and fenced blocks."""
    text = re.sub(r"```.*?```", "", body, flags=re.S)
    text = re.sub(r"`[^`]*`", "", text)
    targets = []
    for target in LINK.findall(text):
        target = target.strip().strip("<>").split(" ")[0].split("#")[0]
        if target and not re.match(r"[A-Za-z][A-Za-z0-9+.-]*:", target):
            targets.append(target)
    return targets


def record_problems(path, record):
    problems = list(record["problems"])
    slug = path.stem
    problem = slug_problem(slug)
    if problem:
        problems.append(problem)
    if record["title"] and FILL in record["title"]:
        problems.append(f"`{FILL}` marker in the title")
    for name in REQUIRED:
        if name not in record["bullets"]:
            problems.append(f"missing bullet `{name}`")
    for name, value in record["bullets"].items():
        if FILL in value:
            problems.append(f"`{FILL}` marker in `{name}`")
            continue
        problem = f"empty `{name}`" if not value else CHECKS[name](value)
        if problem:
            problems.append(problem)
    for name, body in record["sections"].items():
        if FILL in body:
            problems.append(f"`{FILL}` marker in `## {label(name)}`")
        elif not body:
            hint = "" if name in REQUIRED_HEADINGS else "; fill it or delete the optional heading"
            problems.append(f"empty section `## {label(name)}`{hint}")
        for target in links(body):
            if not (path.parent / target).resolve().exists():
                problems.append(f"broken link `{target}` in `## {label(name)}`")
    replaced = record["bullets"].get("replaces")
    if replaced and SLUG.fullmatch(replaced) and (path.parent / f"{replaced}.md").exists():
        problems.append(f"replaces `{replaced}` but `{replaced}.md` still exists; delete it")
    return problems


def records(root):
    """Return (path, record) for every record file, sorted by slug; INDEX.md is not a record."""
    folder = store(root)
    if not folder.is_dir():
        return []
    return [(path, parse(path.read_text(encoding="utf-8-sig")))
            for path in sorted(folder.glob("*.md")) if path.name != "INDEX.md"]


def cell(text):
    return text.replace("|", "\\|") or "-"


def index_text(found):
    """One table row per record: global records first, then by scope list, then title."""
    def order(item):
        path, record = item
        scopes = scopes_of(record)
        return (GLOBAL not in scopes, ", ".join(sorted(scopes)), (record["title"] or path.stem).lower(), path.name)
    lines = ["# Constraints index", "", INDEX_NOTE, ""]
    if not found:
        return "\n".join(lines + ["No records.", ""])
    lines += ["| Constraint | Scope | Paths | Origin |", "| --- | --- | --- | --- |"]
    for path, record in sorted(found, key=order):
        title = (record["title"] or path.stem).replace("[", "\\[").replace("]", "\\]")
        paths = ", ".join(f"`{glob}`" for glob in paths_of(record))
        lines.append(f"| [{cell(title)}]({path.name}) | {cell(', '.join(scopes_of(record)))} | {cell(paths)} | "
                     f"{cell(record['bullets'].get('origin', ''))} |")
    return "\n".join(lines + [""])


def render(root):
    found = records(root)
    write(store(root) / "INDEX.md", index_text(found))
    return f"INDEX.md: {len(found)} records"


def check(root):
    root = Path(root)
    found = records(root)
    errors = []
    holders = {}
    for path, record in found:
        legacy = record["bullets"].get("legacy-id")
        if legacy:
            holders.setdefault(legacy, []).append(path)
    for path, record in found:
        name = relative(root, path)
        problems = record_problems(path, record)
        legacy = record["bullets"].get("legacy-id")
        others = [relative(root, other) for other in holders.get(legacy, []) if other != path]
        if others:
            problems.append(f"duplicate legacy-id `{legacy}`, also in " + ", ".join(others))
        errors += [f"{name}: {problem}" for problem in problems]
    index = store(root) / "INDEX.md"
    if index.exists():
        if index.read_text(encoding="utf-8-sig") != index_text(found):
            errors.append(f"{relative(root, index)}: out of date; run `{SCRIPT} render`")
    elif found:
        errors.append(f"{relative(root, index)}: missing; run `{SCRIPT} render`")
    if state_file(root).exists():
        errors.append(f"{relative(root, state_file(root))}: the retired decisions table still exists; run "
                      f"`{SCRIPT} migrate`, review the records, then delete it")
    global_count = sum(1 for _, record in found if scopes_of(record) == [GLOBAL])
    if global_count > GLOBAL_LIMIT:
        print(f"Warning: {global_count} records have scope `global`, above {GLOBAL_LIMIT}; give each record "
              f"the scopes or paths it applies to, and keep `global` for rules no paths can express.")
    for line in errors:
        print(line)
    if errors:
        print(f"Constraints check failed: {len(errors)} problems")
        return 1
    print(f"Constraints OK: {len(found)} records")
    return 0


def matches(record, scopes, paths):
    own = scopes_of(record)
    if GLOBAL in own:
        return True
    if not scopes and not paths:
        return True
    if set(own) & set(scopes):
        return True
    return any(fnmatch.fnmatchcase(path, glob) for path in paths for glob in paths_of(record))


def listed(root, scopes, paths):
    root = Path(root)
    wanted = [item for value in scopes for item in split_list(value) if item]
    targets = [re.sub(r"^(\./)+", "", item.replace("\\", "/"))
               for value in paths for item in split_list(value) if item]
    return [f"{relative(root, path)} [{', '.join(scopes_of(record))}]: {record['title'] or path.stem}"
            for path, record in records(root) if matches(record, wanted, targets)]


def scaffold(title, bullets, sections):
    """Write the sections given, in heading order; `new` passes all four so authors see the optional ones."""
    lines = [f"# {title}", ""]
    lines += [f"- **{name}**: {bullets[name]}" for name in BULLETS if bullets.get(name)]
    for name in HEADINGS:
        if name in sections:
            lines += ["", f"## {name}", "", sections[name]]
    return "\n".join(lines) + "\n"


def new(root, args):
    folder = store(root)
    path = folder / f"{args.slug}.md"
    bullets = {"origin": args.origin, "scope": ", ".join(split_list(args.scope)),
               "paths": ", ".join(item for value in args.paths or () for item in split_list(value)),
               "date": args.date or dt.date.today().isoformat(), "replaces": args.replaces}
    problems = [slug_problem(args.slug)]
    if not args.title.strip() or "\n" in args.title:
        problems.append("give a one-line title")
    for name, value in bullets.items():
        if value and value != FILL:
            problems.append(CHECKS[name](value))
    problems = [problem for problem in problems if problem]
    if problems:
        return 2, "Constraint error: " + "; ".join(problems)
    if path.exists():
        return 2, f"Constraint error: {relative(Path(root), path)} already exists; choose another slug"
    old = folder / f"{args.replaces}.md" if args.replaces else None
    if old is not None and (not old.is_file() or args.replaces == args.slug):
        return 2, f"Constraint error: --replaces names no record: {relative(Path(root), old)}"
    write(path, scaffold(args.title.strip(), bullets, dict.fromkeys(HEADINGS, FILL)))
    # Hazard: this deletes a tracked record; the slug check above keeps --replaces inside the store.
    if old is not None:
        old.unlink()
    lines = [f"Created {relative(Path(root), path)}"]
    if old is not None:
        lines.append(f"Deleted {relative(Path(root), old)}")
    lines.append(render(root))
    return 0, "\n".join(lines)


def table_rows(text):
    """Return {ID: (decision, rationale, status, date)} from the first ID/Decision/Rationale/Status/Date table,
    plus the rows that cannot be read. Cells may hold `\\|` for a literal pipe."""
    wanted = ["id", "decision", "rationale", "status", "date"]
    columns, rows, broken = None, {}, []
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            if columns is not None:
                break
            continue
        cells = [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", line)[1:-1]]
        if columns is None:
            lowered = [cell.lower() for cell in cells]
            if all(name in lowered for name in wanted):
                columns = [lowered.index(name) for name in wanted]
            continue
        if all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells):
            continue
        if len(cells) <= max(columns):
            broken.append(line)
            continue
        row = [cells[index] for index in columns]
        rows[row[0]] = tuple(row[1:])
    if columns is None:
        raise ValueError("no `| ID | Decision | Rationale | Status | Date |` table found")
    return rows, broken


def migrated_stem(row_id, decision):
    ascii_text = unicodedata.normalize("NFKD", decision).encode("ascii", "ignore").decode().lower()
    words = re.findall(r"[a-z0-9]+", ascii_text)[:5]
    stem = "-".join([row_id.lower()] + words)
    while len(stem) > STEM_LIMIT and "-" in stem:
        stem = stem.rsplit("-", 1)[0]
    return stem


def migrated_title(decision):
    sentence = re.split(r"(?<=[.!?])\s+", decision.strip(), maxsplit=1)[0].strip()
    return sentence.rstrip(".").strip() or FILL


def migrated_origin(decision, rationale):
    text = f"{decision} {rationale}"
    feature = re.search(r"\bfeature\s+`?([a-z0-9]+(?:-[a-z0-9]+)*)`?", text, re.I)
    if feature:
        return f"feature {feature[1].lower()}"
    teams = list(dict.fromkeys(f"D-{number}" for number in re.findall(r"\bD-(\d{2,})\b", text)))
    if teams:
        return "team " + ", ".join(teams)
    # Why: STATE.md rows name ADRs in free text, not by path, so the developer fills in the path.
    return f"adr {FILL}" if re.search(r"\bADRs?\b", text, re.I) else FILL


def git_state(root, ref):
    result = subprocess.run(["git", "show", f"{ref}:./.specs/STATE.md"], cwd=root, capture_output=True)
    if result.returncode:
        raise ValueError(f"git show {ref}:./.specs/STATE.md failed: "
                         + result.stderr.decode("utf-8", "replace").strip())
    return result.stdout.decode("utf-8-sig", "replace")


def migrate(root, since=None):
    root = Path(root)
    state = state_file(root)
    if not state.is_file():
        raise ValueError(f"{relative(root, state)} not found; nothing to migrate")
    rows, broken = table_rows(state.read_text(encoding="utf-8-sig"))
    before = table_rows(git_state(root, since))[0] if since else None
    held = {record["bullets"].get("legacy-id"): path for path, record in records(root)}
    created, skipped, refused = [], [], [f"row `{line}`: cannot read its cells" for line in broken]
    for row_id, (decision, rationale, status, date) in rows.items():
        if before is not None and row_id in before:
            if before[row_id] == (decision, rationale, status, date):
                skipped.append(f"{row_id}: unchanged since {since}")
            else:
                refused.append(f"{row_id}: changed since {since}; supersede its record by hand")
            continue
        if not LEGACY_ID.fullmatch(row_id):
            refused.append(f"{row_id}: not an AD-NNN ID")
        elif status.lower() != "active":
            skipped.append(f"{row_id}: status `{status}`")
        elif row_id in held:
            skipped.append(f"{row_id}: legacy-id already in {relative(root, held[row_id])}")
        else:
            path = store(root) / f"{migrated_stem(row_id, decision)}.md"
            if path.exists():
                refused.append(f"{row_id}: {relative(root, path)} exists with another legacy-id")
                continue
            bullets = {"origin": migrated_origin(decision, rationale), "scope": GLOBAL, "date": date or FILL,
                       "legacy-id": row_id}
            # STATE.md rows carry no trade-offs or open points, so the optional sections stay out.
            sections = {"Decision": decision or FILL, "Why": rationale or FILL}
            write(path, scaffold(migrated_title(decision), bullets, sections))
            held[row_id] = path
            created.append(f"{relative(root, path)} ({row_id})")
    lines = [f"Created {item}" for item in created] + [f"Skipped {item}" for item in skipped]
    lines += [f"Refused {item}" for item in refused]
    lines.append(render(root))
    lines.append(
        f"Next: {relative(root, state)} stays in place. Review each new record with the developer. Delete a "
        "record unless an agent must conform to it and could not infer it from the code. Replace scope "
        "`global` with the areas it applies to and add paths where globs can express it. Replace every "
        f"`{FILL}`. Then delete {relative(root, state)} and run `{SCRIPT} check`.")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Constraint records for coding agents under .specs/constraints/.")
    commands = parser.add_subparsers(dest="action", required=True)
    for name in ("new", "check", "list", "render", "migrate"):
        command = commands.add_parser(name)
        command.add_argument("--root", type=Path, default=Path.cwd(), help="Project root; defaults to the current folder")
        if name == "new":
            command.add_argument("--slug", required=True)
            command.add_argument("--title", required=True)
            command.add_argument("--origin", required=True)
            command.add_argument("--scope", required=True, help="Comma-separated areas, or global")
            command.add_argument("--paths", nargs="+", help="Relative globs, such as src/api/**")
            command.add_argument("--replaces", help="Slug of the record this one supersedes; it is deleted")
            command.add_argument("--date", help="YYYY-MM-DD; defaults to today")
        elif name == "list":
            command.add_argument("--scope", action="append", default=[], help="Comma-separated areas")
            command.add_argument("--paths", nargs="+", default=[], help="Paths the change touches")
        elif name == "migrate":
            command.add_argument("--since", metavar="REF", help="Convert only rows added after this Git ref")
    args = parser.parse_args(argv)
    try:
        if args.action == "check":
            return check(args.root)
        if args.action == "new":
            code, message = new(args.root, args)
            print(message, file=sys.stderr if code else sys.stdout)
            return code
        if args.action == "render":
            print(render(args.root))
        elif args.action == "list":
            print("\n".join(listed(args.root, args.scope, args.paths)) or "No matching constraints")
        else:
            print(migrate(args.root, args.since))
    except (ValueError, OSError) as error:
        print(f"Constraint error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    sys.exit(main())
