"""Project-local, report-backed lesson bookkeeping. Standard library only.

Each lesson is one file, .specs/lessons/<hash>.json, named by a hash of its project, repository,
area scope, and text, so two developers adding different lessons never touch the same file. The
file is shared, so it holds only the sentence, the area scope, the status, and one
{feature, signal} entry per feature that saw it or penalized it. The cited round in the git-ignored
feature folder keeps the evidence; ingest and penalize verify it but never copy it. LESSONS.md is
generated. A store written by an earlier schema needs `migrate` before any write action.
"""

import argparse
import datetime as dt
import hashlib
import json
import re
from pathlib import Path

SIGNALS = {"ac_gap", "surviving_mutant", "spec_precision_gap", "spec_deviation", "gate_fail"}
PROMOTE, QUARANTINE, WINDOW_DAYS = 2, 2, 45
SCHEMA = 3
LESSON_FILE = re.compile(r"^[0-9a-f]{12}\.json$")
# An area scope: slug segments joined by single slashes, such as apps/web or billing-webhooks.
AREA = re.compile(r"[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*")
AREA_LENGTH = 64
# Personal or review-bound details that make a shared lesson sentence useless to a teammate.
# Bare hostnames and workspace names have no reliable pattern, so they are not detected.
PERSONAL = [
    ("a checkpoint or mutation ID", re.compile(r"\b[CM]\d+\b")),
    ("a commit hash", re.compile(r"\b(?=[0-9a-f]*\d)(?=[0-9a-f]*[a-f])[0-9a-f]{7,64}\b", re.I)),
    ("a commit range", re.compile(r"\b[0-9a-f]{7,64}\.\.\.?[0-9a-f]{7,64}\b", re.I)),
    ("a file:line reference", re.compile(r"\b[\w-]+\.\w+:\d+")),
    # A path and a route look alike, so only well-known system folders, home, drive, and UNC
    # paths count as personal; any other leading-slash text, such as /items, is read as a route.
    ("an absolute or home path", re.compile(
        r"(?<![\w./-])/(?:home|Users|root|tmp|var|opt|mnt|srv|workspaces?|private|usr|etc)/"
        r"|~[/\\]|\b[A-Za-z]:[\\/]|\\\\")),
    ("a URL", re.compile(r"://")),
    ("a user@host", re.compile(r"\b\w[\w.-]*@\w[\w.-]*\b")),
]


def normalized(text):
    return " ".join(re.findall(r"\w+", text.casefold()))


def store(root):
    return Path(root) / ".specs" / "lessons"


def lesson_id(project, repository, scope, text):
    key = "\n".join((project, repository, scope, normalized(text)))
    return hashlib.sha256(key.encode("utf-8")).hexdigest()[:12]


def enabled(root):
    path = store(root) / "settings.json"
    return not path.exists() or json.loads(path.read_text(encoding="utf-8")).get("enabled", True) is not False


def load(root):
    folder = store(root)
    if not folder.is_dir():
        return []
    items = [json.loads(path.read_text(encoding="utf-8"))
             for path in sorted(folder.iterdir()) if LESSON_FILE.match(path.name)]
    return sorted(items, key=lambda item: (item["created"], item["id"]))


def writable(root):
    """Write actions refuse a store that still holds files from an earlier schema."""
    old = [item["id"] for item in load(root) if item.get("schema") != SCHEMA]
    if old:
        raise ValueError(f"{len(old)} lesson file(s) use an earlier schema; "
                         f"run `lessons.py migrate --root <project-root>` first")


def save(root, item):
    path = store(root) / f'{item["id"]}.json'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(item, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def render(root):
    """Regenerate LESSONS.md from the lesson files; after a merge, run this instead of editing it."""
    confirmed = [item for item in load(root) if item["status"] == "confirmed"]
    lines = ["# Confirmed project lessons", "",
             "Generated by lessons.py from .specs/lessons/. Do not edit or merge by hand; run "
             "`lessons.py render`. Check current requirements before applying a lesson.", ""]
    for item in confirmed:
        lines.append(f'- {item["id"]} [{item["project"]}/{item["repository"]}/{item["scope"]}]: {item["text"]}')
    path = Path(root) / ".specs" / "LESSONS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return f"LESSONS.md: {len(confirmed)} confirmed"


def report_signal(root, relative, revision, signal_id, signal_type):
    """Prove the cited signal is real. The caller stores only its feature and type."""
    root = Path(root).resolve()
    path = (root / relative).resolve()
    if root not in path.parents or not path.is_file():
        raise ValueError("Report must be a file inside the project")
    content = path.read_bytes()
    if hashlib.sha256(content).hexdigest() != revision:
        raise ValueError("Report revision differs from citation")
    report = json.loads(content)
    signals = [item for item in report.get("signals", [])
               if item.get("id") == signal_id and item.get("type") == signal_type]
    if len(signals) != 1 or signal_type not in SIGNALS:
        raise ValueError("Signal is missing, ambiguous, or unsupported")
    signal = signals[0]
    if signal_type in ("ac_gap", "spec_precision_gap", "spec_deviation") and not any(
            row.get("id") == signal.get("checkpoint") and row.get("verdict") in ("FAIL", "GAP")
            for row in report.get("checkpoints", [])):
        raise ValueError("Signal lacks a failed or uncovered checkpoint")
    if signal_type == "surviving_mutant" and signal.get("detected") is not False:
        raise ValueError("Mutation did not survive")
    if signal_type == "gate_fail" and signal.get("exit_code", 0) == 0:
        raise ValueError("Gate did not fail")
    return report, signal


def area_problem(scope, features):
    """Return why `scope` is not an area slug, or None when it is one."""
    if not isinstance(scope, str) or not AREA.fullmatch(scope) or len(scope) > AREA_LENGTH:
        return (f"scope {scope!r} must be an area: letters, digits, '.', '_', or '-', joined by single '/', "
                f"at most {AREA_LENGTH} characters")
    if any(part in (".", "..") for part in scope.split("/")):
        return f"scope {scope!r} must not hold a '.' or '..' segment"
    if any(scope.casefold() == str(feature).casefold() for feature in features):
        return f"scope {scope!r} names a feature; scope the lesson to an area"
    return None


def check_scope(scope, features):
    problem = area_problem(scope, features)
    if problem:
        raise ValueError(problem)


def check_text(text, report, feature):
    """Reject a sentence that names the feature, a round ID, or a personal or review-bound detail."""
    named = [feature] + [row["id"] for key in ("checkpoints", "mutations", "signals")
                         for row in report.get(key) or []
                         if isinstance(row, dict) and isinstance(row.get("id"), str) and row["id"]]
    for name in named:
        if re.search(rf"(?<!\w){re.escape(name)}(?!\w)", text, re.I):
            raise ValueError(f"Lesson text names {name!r} from the round; write the reusable mechanism")
    for kind, pattern in PERSONAL:
        if pattern.search(text):
            raise ValueError(f"Lesson text holds {kind}; write the reusable mechanism without it")


def sighting(feature, signal_type):
    return {"feature": feature, "signal": signal_type}


def prune(root):
    writable(root)
    limit = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=WINDOW_DAYS)
    removed = 0
    for item in load(root):
        if item["status"] == "candidate" and dt.datetime.fromisoformat(item["created"]) < limit:
            (store(root) / f'{item["id"]}.json').unlink()
            removed += 1
    render(root)
    return f"Pruned {removed} stale candidate(s)"


def ingest(root, args):
    if not enabled(root):
        return "Lesson processing disabled; report retained"
    writable(root)
    report, _ = report_signal(root, args.report, args.revision, args.signal_id, args.signal)
    if not all((args.feature, args.project, args.repository, args.scope, args.text)):
        raise ValueError("Stable feature, project, repository, scope, and text required")
    if (report.get("feature_id"), report.get("project"), report.get("repository")) != (
            args.feature, args.project, args.repository):
        raise ValueError("Report identity differs from observation: feature_id, project, or repository")
    check_scope(args.scope, [args.feature])
    check_text(args.text, report, args.feature)
    prune(root)
    key = lesson_id(args.project, args.repository, args.scope, args.text)
    path = store(root) / f"{key}.json"
    item = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {
        "schema": SCHEMA, "id": key, "project": args.project, "repository": args.repository,
        "scope": args.scope, "text": args.text, "status": "candidate",
        "created": dt.datetime.now(dt.timezone.utc).isoformat(), "observations": [], "penalties": []}
    if not any(entry["feature"] == args.feature for entry in item["observations"]):
        item["observations"].append(sighting(args.feature, args.signal))
    if item["status"] == "candidate" and len(item["observations"]) >= PROMOTE:
        item["status"] = "confirmed"
    save(root, item)
    render(root)
    return f'{item["id"]}: {item["status"]}'


def penalize(root, args):
    if not enabled(root):
        return "Lesson processing disabled; report retained"
    writable(root)
    known = bool(args.lesson_id) and LESSON_FILE.match(f"{args.lesson_id}.json")
    path = store(root) / f"{args.lesson_id}.json"
    item = json.loads(path.read_text(encoding="utf-8")) if known and path.exists() else None
    if item is None or item["status"] not in ("confirmed", "quarantined"):
        raise ValueError("Penalty requires a confirmed lesson")
    report, signal = report_signal(root, args.report, args.revision, args.signal_id, args.signal)
    project = getattr(args, "project", None) or item["project"]
    repository = getattr(args, "repository", None) or item["repository"]
    if (signal.get("loaded_lesson") != item["id"] or not args.feature
            or report.get("feature_id") != args.feature
            or report.get("project") != item["project"] or project != item["project"]
            or report.get("repository") != item["repository"] or repository != item["repository"]):
        raise ValueError("Report does not show this loaded lesson failing in a feature")
    if not any(penalty["feature"] == args.feature for penalty in item["penalties"]):
        item["penalties"].append(sighting(args.feature, args.signal))
    if len(item["penalties"]) >= QUARANTINE:
        item["status"] = "quarantined"
    save(root, item)
    render(root)
    return f'{item["id"]}: {item["status"]}'


def stripped(entries):
    """Earlier schemas copied the whole signal; keep one feature and signal type per feature."""
    kept = []
    for entry in entries or []:
        signal = entry.get("signal")
        kind = signal.get("type") if isinstance(signal, dict) else signal
        if entry.get("feature") and not any(row["feature"] == entry["feature"] for row in kept):
            kept.append(sighting(entry["feature"], kind if isinstance(kind, str) and kind else "unknown"))
    return kept


def migrate(root):
    """Rewrite earlier-schema files as schema 3 and list every lesson whose scope is not an area."""
    migrated, lines = 0, []
    for item in load(root):
        if item.get("schema") != SCHEMA:
            item = {"schema": SCHEMA,
                    **{key: item[key] for key in ("id", "project", "repository", "scope", "text",
                                                  "status", "created")},
                    "observations": stripped(item.get("observations")),
                    "penalties": stripped(item.get("penalties"))}
            save(root, item)
            migrated += 1
        if area_problem(item["scope"], [row["feature"] for row in item["observations"]]):
            lines.append(f'{item["id"]}: rescope with --scope AREA')
    render(root)
    return "\n".join(lines + [f"Migrated {migrated} lesson file(s)"])


def rescope(root, args):
    """Move a lesson to an area scope, merging sightings with any lesson already at the new ID."""
    writable(root)
    known = bool(args.lesson_id) and LESSON_FILE.match(f"{args.lesson_id}.json")
    old_path = store(root) / f"{args.lesson_id}.json"
    if not known or not old_path.exists():
        raise ValueError(f"Unknown lesson ID: {args.lesson_id}")
    item = json.loads(old_path.read_text(encoding="utf-8"))
    check_scope(args.scope, [row["feature"] for row in item["observations"]])
    key = lesson_id(item["project"], item["repository"], args.scope, item["text"])
    new_path = store(root) / f"{key}.json"
    other = json.loads(new_path.read_text(encoding="utf-8")) if key != item["id"] and new_path.exists() else None
    merged = {**item, "id": key, "scope": args.scope}
    statuses = {item["status"]}
    if other:
        check_scope(args.scope, [row["feature"] for row in other["observations"]])
        for name in ("observations", "penalties"):
            merged[name] = item[name] + [row for row in other[name]
                                         if not any(own["feature"] == row["feature"] for own in item[name])]
        merged["created"] = min(item["created"], other["created"], key=dt.datetime.fromisoformat)
        statuses.add(other["status"])
    if len(merged["penalties"]) >= QUARANTINE or "quarantined" in statuses:
        merged["status"] = "quarantined"
    elif len(merged["observations"]) >= PROMOTE:
        merged["status"] = "confirmed"
    else:
        merged["status"] = "candidate"
    save(root, merged)
    if key != item["id"]:
        old_path.unlink()
    render(root)
    return f'{item["id"]} -> {key}: {merged["status"]}'


def listed(root, args):
    return [f'{item["id"]}: {item["text"]}' for item in load(root)
            if item["status"] == "confirmed"
            and (not args.project or item["project"] == args.project)
            and (not args.repository or item["repository"] == args.repository)
            and (not args.scope or item["scope"] == args.scope)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("ingest", "penalize", "list", "prune", "render", "migrate", "rescope"))
    parser.add_argument("--root", type=Path, required=True)
    for name in ("report", "revision", "signal-id", "signal", "feature", "project",
                 "repository", "scope", "text", "lesson-id"):
        parser.add_argument("--" + name)
    args = parser.parse_args()
    try:
        if args.action == "ingest":
            print(ingest(args.root, args))
        elif args.action == "penalize":
            print(penalize(args.root, args))
        elif args.action == "prune":
            print(prune(args.root))
        elif args.action == "render":
            print(render(args.root))
        elif args.action == "migrate":
            print(migrate(args.root))
        elif args.action == "rescope":
            print(rescope(args.root, args))
        else:
            print("\n".join(listed(args.root, args)) or "No confirmed lessons")
    except (ValueError, TypeError, KeyError, FileNotFoundError, json.JSONDecodeError) as error:
        parser.exit(2, f"Lesson error: {error}\n")


if __name__ == "__main__":
    main()
